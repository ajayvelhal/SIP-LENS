// scripts/lib/cas-layout.mjs
// Pure page layout for synthetic CAS PDFs: decides every text line, its x/y position and its page, so the
// golden builder knows the page of each transaction before anything is drawn. cas-pdf.mjs only draws
// what this module returns. No dependencies.

import { fmtDate, fmtMoney, fmtUnits, fmtNav, groupIndian, INVESTORS, maskedPan } from './synthetic.mjs';

export const PAGE = { w: 595.28, h: 841.89 };            // A4 in points
export const FONT = { size: 7.5, lineHeight: 10, charWidth: 3.9 }; // Helvetica average advance at 7.5 pt
export const MARGIN = { top: 56, bottom: 792, headerY: 26, footerY: 812, left: 36, right: 559 };

/** Column anchors per RTA style. Numeric columns are right-aligned at `x`. */
export const COLUMNS = {
  cams: { date: { x: 36, align: 'left' }, desc: { x: 92, align: 'left', width: 190 }, amount: { x: 395, align: 'right' }, units: { x: 455, align: 'right' }, nav: { x: 515, align: 'right' }, balance: { x: 572, align: 'right' } },
  kfin: { date: { x: 40, align: 'left' }, desc: { x: 100, align: 'left', width: 170 }, amount: { x: 380, align: 'right' }, units: { x: 445, align: 'right' }, nav: { x: 505, align: 'right' }, balance: { x: 570, align: 'right' } },
};

const RTA_FOOTER = {
  cams: 'CAMS | Computer Age Management Services Limited | Registrar & Transfer Agent',
  kfin: 'KFin Technologies Limited | Registrar & Transfer Agent',
};
const SYNTHETIC_FOOTER = 'SYNTHETIC STATEMENT generated by sip-lens scripts/gen-fixtures.mjs. Every investor, folio, PAN, fund and number is fictitious.';

export function wrapText(text, maxChars) {
  const words = text.split(' ');
  const lines = [];
  let cur = '';
  for (const w of words) {
    if (!cur) { cur = w; continue; }
    if ((cur + ' ' + w).length <= maxChars) cur += ' ' + w;
    else { lines.push(cur); cur = w; }
  }
  if (cur) lines.push(cur);
  return lines;
}

class Writer {
  constructor(style, opts = {}) {
    this.style = style;
    this.opts = opts;
    this.pages = [];
    this.y = Infinity;
    this.lineCount = 0;
    this.textChars = 0;
    this.rowPage = new Map();
    this.sectionPage = new Map();
    this.pageSplitRows = 0;
  }
  get page() { return this.pages.length; }
  newPage() {
    const lines = [];
    this.pages.push({ number: this.pages.length + 1, lines });
    this.y = MARGIN.top;
    // Repeated header and footer rows: same y on every page (design E52 drops them).
    this.raw(MARGIN.headerY, [{ x: MARGIN.left, text: this.opts.headerTitle ?? 'Consolidated Account Statement', align: 'left' }, { x: MARGIN.right, text: `Page ${this.page} of {PAGES}`, align: 'right' }], 'page-header');
    this.raw(MARGIN.footerY, [{ x: MARGIN.left, text: this.opts.footer ?? RTA_FOOTER[this.style], align: 'left' }], 'page-footer');
    this.raw(MARGIN.footerY + FONT.lineHeight, [{ x: MARGIN.left, text: SYNTHETIC_FOOTER, align: 'left', size: 6 }], 'page-footer');
  }
  raw(y, cells, role, ref) {
    const pg = this.pages[this.pages.length - 1];
    pg.lines.push({ y, cells, role, ref });
    this.lineCount++;
    for (const c of cells) this.textChars += c.text.length;
  }
  ensure(lines = 1) {
    if (this.pages.length === 0 || this.y + (lines - 1) * FONT.lineHeight > MARGIN.bottom) this.newPage();
  }
  line(cells, role = 'text', ref) {
    this.ensure(1);
    this.raw(this.y, cells, role, ref);
    this.y += FONT.lineHeight;
  }
  text(str, role = 'text', x = MARGIN.left) {
    this.line([{ x, text: str, align: 'left' }], role);
  }
  gap(n = 0.6) { this.y += FONT.lineHeight * n; }
}

function folioHeaderText(f, fx) {
  const inv = INVESTORS[f.investor];
  const pan = fx.style === 'kfin' ? maskedPan(inv.pan) : inv.pan;
  return `Folio No: ${f.folioNumber}    PAN: ${pan}    KYC: OK    PAN: OK`;
}

function schemeHeaderLines(h, f, fx) {
  const s = h.scheme;
  const registrar = f.rta === 'CAMS' ? 'CAMS' : 'KFINTECH';
  const advisor = s.name.includes('Direct') ? 'DIRECT' : 'ARN-000000';
  const lines = [{ text: s.amc, role: 'amc' }];
  if (fx.style === 'cams') {
    const code = s.code ? `${s.code}G` : 'VD01';
    lines.push({ text: `${code}-${h.printedName} (Advisor: ${advisor}) Registrar : ${registrar}`, role: 'scheme' });
    if (s.isin) lines.push({ text: `ISIN: ${s.isin}`, role: 'isin' });
  } else {
    lines.push({ text: `${h.printedName}`, role: 'scheme' });
    lines.push({ text: `${s.isin ? `ISIN: ${s.isin}  ` : ''}(Advisor: ${advisor})  Registrar : ${registrar}`, role: 'isin' });
  }
  return lines;
}

function columnHeader(style) {
  const c = COLUMNS[style];
  return [
    { x: c.date.x, text: 'Date', align: 'left' }, { x: c.desc.x, text: 'Transaction', align: 'left' },
    { x: c.amount.x, text: 'Amount (INR)', align: 'right' }, { x: c.units.x, text: 'Units', align: 'right' },
    { x: c.nav.x, text: 'NAV (INR)', align: 'right' }, { x: c.balance.x, text: 'Unit Balance', align: 'right' },
  ];
}

function rowCells(row, style, dp) {
  const c = COLUMNS[style];
  const nums = [];
  if (row.amountPaise !== undefined) nums.push({ x: c.amount.x, text: fmtMoney(row.amountPaise / 100, style), align: 'right' });
  if (row.unitsInt !== undefined) nums.push({ x: c.units.x, text: fmtUnits(row.unitsInt / 10 ** dp, dp, style), align: 'right' });
  if (row.nav !== undefined) nums.push({ x: c.nav.x, text: fmtNav(row.nav), align: 'right' });
  if (row.printBalance && row.balanceInt !== undefined) nums.push({ x: c.balance.x, text: fmtUnits(row.balanceInt / 10 ** dp, dp, style), align: 'right' });
  return nums;
}

function closingLines(h, fx, style, dp) {
  const asOf = fmtDate(fx.period.to);
  const units = fmtUnits(h.closingInt / 10 ** dp, dp, style);
  const cost = groupIndian(h.costPaise / 100, 2);
  const value = groupIndian(h.closingValuePaise / 100, 2);
  if (fx.kind === 'summary') {
    return [
      `Closing Unit Balance: ${units}    NAV on ${asOf}: INR ${fmtNav(h.closingNav)}`,
      `Cost Value: INR ${cost}    Market Value on ${asOf}: INR ${value}`,
    ];
  }
  return [
    `Closing Unit Balance: ${units}    NAV on ${asOf}: INR ${fmtNav(h.closingNav)}`,
    `Total Cost Value: INR ${cost}    Market Value on ${asOf}: INR ${value}`,
  ];
}

/**
 * Lays out a detailed or summary CAS. Returns { pages, rowPage, sectionPage, lineCount, textChars, pageSplitRows }.
 * `expanded` is expandFixture()'s output.
 */
export function layoutCas(expanded) {
  const fx = expanded.fixture;
  const style = fx.style;
  const dp = expanded.dp;
  const w = new Writer(style);
  const c = COLUMNS[style];
  const descChars = Math.floor(c.desc.width / FONT.charWidth);
  w.newPage();

  // Title block (page 1 only)
  w.line([{ x: MARGIN.left, text: 'Consolidated Account Statement', align: 'left', size: 11, bold: true }], 'title');
  if (!fx.omitPeriodLine) w.text(`${fmtDate(fx.period.from)} To ${fmtDate(fx.period.to)}`, 'period');
  w.text(fx.kind === 'summary' ? 'Statement Type: Summary' : 'Statement Type: Detailed', 'meta');
  w.gap();

  let lastInvestor = null;
  let splitForced = false;
  for (const f of expanded.folios) {
    if (f.investor !== lastInvestor) {
      const inv = INVESTORS[f.investor];
      w.gap(0.4);
      w.text(inv.name, 'investor');
      for (const a of inv.address) w.text(a, 'address');
      w.text(`Email Id: ${inv.email}`, 'email');
      w.text(`Mobile: ${inv.mobile}`, 'mobile');
      w.gap();
      lastInvestor = f.investor;
    }
    w.ensure(4);
    w.line([{ x: MARGIN.left, text: folioHeaderText(f, fx), align: 'left', bold: true }], 'folio');
    for (const h of f.holdings) {
      // cost value for the closing row: everything the investor paid in (purchase-like amounts + stamp duty)
      h.costPaise = h.rows.filter((r) => !r.hidden && ['purchase', 'sip', 'switch_in', 'stamp_duty'].includes(r.kind) && r.amountPaise > 0).reduce((a, r) => a + r.amountPaise, 0);
      const copies = h.duplicate ? 2 : 1;
      for (let copy = 0; copy < copies; copy++) {
        w.ensure(7);
        const header = schemeHeaderLines(h, f, fx);
        if (copy === 0) w.sectionPage.set(h, w.page);
        else h.duplicatePage = w.page;
        for (const l of header) w.text(l.text, l.role);
        if (fx.kind === 'detailed') {
          w.text(`Opening Unit Balance: ${fmtUnits(h.openingInt / 10 ** dp, dp, style)}`, 'opening');
          w.line(columnHeader(style), 'columns');
          for (const row of h.rows) {
            if (row.hidden) continue;
            const descLines = wrapText(row.description, descChars);
            const nums = rowCells(row, style, dp);
            const numbersOnLast = style === 'kfin';
            if (fx.forceSplit && !splitForced && descLines.length > 1) {
              // E51: park the cursor on the last body line so this row's continuation lands on the next page.
              const remaining = Math.floor((MARGIN.bottom - w.y) / FONT.lineHeight) + 1;
              if (remaining >= 2) { w.y += (remaining - 1) * FONT.lineHeight; splitForced = true; }
            }
            let firstLinePage = null;
            for (let i = 0; i < descLines.length; i++) {
              const cells = [];
              if (i === 0) cells.push({ x: c.date.x, text: fmtDate(row.date), align: 'left' });
              cells.push({ x: c.desc.x, text: descLines[i], align: 'left' });
              const isNumbersLine = numbersOnLast ? i === descLines.length - 1 : i === 0;
              if (isNumbersLine) cells.push(...nums);
              w.line(cells, i === 0 ? 'row' : 'row-continuation', row);
              if (i === 0) firstLinePage = w.page;
            }
            if (copy === 0) {
              w.rowPage.set(row, firstLinePage);
              if (w.page !== firstLinePage) w.pageSplitRows++;
            }
          }
          if (!h.noClosing) {
            const cl = closingLines(h, fx, style, dp);
            w.ensure(2);
            if (copy === 0) h.closingPage = w.page;
            for (const t of cl) w.line([{ x: MARGIN.left, text: t, align: 'left', bold: true }], 'closing');
          } else if (copy === 0) {
            h.lastRowPage = w.page;
          }
        } else {
          const cl = closingLines(h, fx, style, dp);
          w.ensure(2);
          if (copy === 0) h.closingPage = w.page;
          for (const t of cl) w.line([{ x: MARGIN.left, text: t, align: 'left', bold: true }], 'closing');
        }
        w.gap(0.8);
      }
    }
    w.gap(0.6);
  }
  // Repeated column headers after page breaks inside a table (insert as the first body line of such pages).
  insertContinuationHeaders(w, style);
  return finish(w);
}

/** Pages whose first body line is a transaction row get a column header line inserted above it. */
function insertContinuationHeaders(w, style) {
  for (const pg of w.pages) {
    const body = pg.lines.filter((l) => l.role !== 'page-header' && l.role !== 'page-footer');
    if (!body.length) continue;
    const first = body[0];
    if (first.role === 'row' || first.role === 'row-continuation') {
      // shift body lines down by one line height and insert the header at the top
      for (const l of body) l.y += FONT.lineHeight;
      pg.lines.push({ y: MARGIN.top, cells: columnHeader(style), role: 'columns' });
      w.lineCount++;
    }
  }
}

function finish(w) {
  const pageCount = w.pages.length;
  for (const pg of w.pages) for (const l of pg.lines) for (const cell of l.cells) cell.text = cell.text.replace('{PAGES}', String(pageCount));
  for (const pg of w.pages) pg.lines.sort((a, b) => a.y - b.y);
  return { pages: w.pages, rowPage: w.rowPage, sectionPage: w.sectionPage, lineCount: w.lineCount, textChars: w.textChars, pageSplitRows: w.pageSplitRows, pageCount };
}

