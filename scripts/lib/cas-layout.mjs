  const w = new Writer('cams', { headerTitle: 'Lens Sample Bank - Account Statement', footer: 'Lens Sample Bank Limited (fictitious)' });
  w.newPage();
  w.line([{ x: MARGIN.left, text: 'Account Statement', align: 'left', size: 11, bold: true }], 'title');
  w.text('Account No: XXXXXX1234    Branch: Fictional Road    Period: 01-Mar-2025 to 31-Mar-2025');
  w.gap();
  w.text('Date          Narration                                  Debit        Credit       Balance');
  const rows = [['03-Mar-2025', 'UPI/Sample Grocer', '1,250.00', '', '48,750.00'], ['07-Mar-2025', 'NEFT Salary', '', '85,000.00', '1,33,750.00'], ['10-Mar-2025', 'ACH Debit Sample SIP', '5,000.00', '', '1,28,750.00'], ['31-Mar-2025', 'Interest Credit', '', '212.00', '1,28,962.00']];
