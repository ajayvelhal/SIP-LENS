export function layoutDepository(fx) {
  const inv = INVESTORS.primary;
  const nsdl = fx.depository === 'NSDL';
  const w = new Writer('cams', { headerTitle: nsdl ? 'NSDL Consolidated Account Statement' : 'CDSL Consolidated Account Statement', footer: nsdl ? 'National Securities Depository Limited' : 'Central Depository Services (India) Limited | myeasi' });
  w.newPage();
  w.line([{ x: MARGIN.left, text: 'Consolidated Account Statement', align: 'left', size: 11, bold: true }], 'title');
  w.text(`Statement for the period ${fmtDate(fx.period.from)} to ${fmtDate(fx.period.to)}`);
  w.text(nsdl ? 'CAS ID: 1000000001    NSDL e-CAS' : 'BO ID: 1200000000000001    CDSL e-CAS');
  w.gap();
  w.text(inv.name); for (const a of inv.address) w.text(a); w.text(`PAN: ${maskedPan(inv.pan)}`);
  w.gap();
  w.text('Summary of Value of Your Holdings');
  w.text('Asset Class                    Value (INR)        % of Portfolio');
  w.text('Equities (E)                   12,34,567.00       61.2');
  w.text('Mutual Fund Folios (F)         7,82,100.00        38.8');
  w.gap();
  w.text(nsdl ? 'Demat Account: DP ID IN300000  Client ID 10000001  (NSDL)' : 'Demat Account: BO ID 1200000000000001  (CDSL)');
  w.text('ISIN            Security                                  Current Bal.    Market Price    Value');
  w.text('INE000S00001    Lens Sample Industries Ltd                 100             1,234.50        1,23,450.00');
  w.text('INE000S00002    Fictional Bank Ltd                         250             444.40          1,11,100.00');
  w.gap();
  w.text('Mutual Fund Folios (F)  -  serviced by CAMS / KFINTECH');
  w.text('Folio No        Scheme Name                                        Closing Bal.   NAV        Value');
  w.text('91000000000/0   Lens Sample Large Cap Fund - Direct Plan - Growth   1,234.567      44.8284    55,345.67');
  w.gap();
  w.text('This statement is generated by the depository. For mutual fund transactions request a detailed CAS from the RTA.');
  return finish(w);
}

